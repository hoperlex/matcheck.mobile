package com.example.matcheckmobile.domain.model

/**
 * Намерение приложить кадр к операции: «этот исходник из operation_photos
 * должен стать фото приёмки/отгрузки».
 *
 * Intent'ы кладутся в Room в ОДНОЙ транзакции с сущностью и мутацией
 * (DeliveryRepository.upsert / ShipmentRepository.upsert). Тяжёлая часть —
 * декод, два JPEG-энкода и запись main+thumb — выполняется потом,
 * PhotoPrepareWorker'ом, локально и с ретраями.
 *
 * До этого разделения подготовка шла прямо в finalize() формы ПОСЛЕ того, как
 * мутация уже легла в очередь: падение декода (нет места, OOM) означало, что
 * приёмка уедет на сервер вообще без фото и без следа. Так, по всей видимости,
 * и появились 14 приёмок в финальном статусе без единого подтверждённого фото
 * за 09.06–06.07.2026.
 *
 * Разбор начался с другого случая: 12.08.2026 планшет «ЖК Событие 6.1» после
 * четырёх суток офлайна несколько часов показывал приёмки с нулём фото. Там
 * потери не было — кадры догрузились через ~3.7 часа, время съёмки корректное.
 * Но он вскрыл сам дефект: запись всегда уходит на сервер раньше своих фото.
 *
 * @param sourcePath абсолютный путь к исходнику внутри filesDir/operation_photos;
 *   он же — ключ идемпотентности (уникальный индекс parentId+sourcePath).
 * @param takenAt момент съёмки по часам планшета, ISO-8601. Считается один раз
 *   здесь, пока файл ещё на диске: presign позже файл не перечитывает.
 */
data class PhotoIntent(
    val kind: String,
    val stage: String,
    val sourcePath: String,
    val takenAt: String,
)
