package com.example.matcheckmobile.domain.ocr

import com.example.matcheckmobile.domain.validation.PlateReading
import java.io.File

/**
 * Чем закончилась попытка распознать номер на одном кадре.
 *
 * Перечислены ВСЕ выходы, включая ранние: без этого у телеметрии нет знаменателя и долю
 * срабатываний посчитать нельзя. Именно поэтому на вопрос «как часто распознавание
 * работает» после суток эксплуатации ответить было нечем.
 */
enum class PlateOcrOutcome {
    /** Кадр не прочитался с диска. */
    FRAME_READ_FAILED,

    /** Кадр не декодировался — битый JPEG или нехватка памяти. */
    DECODE_FAILED,

    /** OCR-модуль Google Play services ещё не приехал на устройство. */
    MODULE_UNAVAILABLE,

    /** Распознаватель отработал, но номера на кадре не нашёл. */
    NO_FIRST_CANDIDATE,

    /** Рамка найдена, но вырезать её в исходном разрешении не удалось. */
    CROP_FAILED,

    /** Второй проход по вырезанной рамке номера не увидел. */
    NO_SECOND_CANDIDATE,

    /** Прочее падение распознавателя. */
    RECOGNISE_FAILED,

    /** Номер подставлен автоматически. */
    AUTO,

    /** Номер предложен подсказкой. */
    SUGGESTED,
}

/**
 * Результат одной попытки. Возвращается ВСЕГДА, даже когда номера нет: вызывающий обязан
 * записать ровно одно событие телеметрии на каждое фото.
 *
 * Госномер лежит только в [reading]; в журнал он не попадает — туда уходят [outcome],
 * габариты и высота текста.
 */
data class PlateOcrResult(
    val outcome: PlateOcrOutcome,
    val reading: PlateReading? = null,
    val frameWidth: Int = 0,
    val frameHeight: Int = 0,
    /** Высота найденного текста в пикселях уменьшенного кадра — по ней видно, хватает ли разрешения. */
    val textHeightPx: Int? = null,
)

/**
 * Распознавание госномера с фотографии.
 *
 * Контракт жёсткий, и на него опирается вызывающий код: **ни один метод не бросает ничего,
 * кроме `CancellationException`**. Распознавание — украшение: нет Google Play services, не
 * приехал модуль, битый кадр, мало памяти — всё это возвращает результат с исходом, но
 * никогда не мешает добавить фотографию.
 *
 * Два шага разнесены нарочно. [readFrame] обязан отработать ДО того, как на кадр ляжет
 * водяной знак: `MetadataWatermark.applyTo` перезаписывает файл неатомарно, и любое
 * последующее чтение того же файла могло бы попасть на полузаписанный JPEG.
 */
interface PlateOcr {

    /** Читает кадр в память целиком. Возвращает null, если прочитать не вышло. */
    suspend fun readFrame(file: File): ByteArray?

    /** Распознаёт номер. Никогда не бросает, кроме отмены. */
    suspend fun recognise(frame: ByteArray): PlateOcrResult
}
