package com.example.matcheckmobile.domain.ocr

import android.graphics.Bitmap
import java.io.File

/**
 * Распознавание госномера с фотографии.
 *
 * Контракт жёсткий, и на него опирается вызывающий код: **ни один метод не бросает
 * ничего, кроме `CancellationException`**. Распознавание — necessity-free украшение:
 * нет Google Play services, не приехал OCR-модуль, битый кадр, мало памяти — всё это
 * возвращает null и логируется, но никогда не мешает добавить фотографию к операции.
 *
 * Два шага разнесены нарочно. [decodeForOcr] обязан отработать ДО того, как на кадр
 * ляжет водяной знак (тот перезаписывает файл и подмешал бы распознавателю собственный
 * текст), а [recognise] уже работает с готовым битмапом и может тянуться сколько угодно,
 * не задерживая появление фотографии на экране.
 */
interface PlateOcr {

    /**
     * Декодирует уменьшенную копию кадра. Возвращает null, если декодировать не вышло.
     */
    suspend fun decodeForOcr(file: File): Bitmap?

    /**
     * Распознаёт номер и возвращает его в кириллице, либо null, если уверенности нет.
     *
     * **Владение [bitmap] переходит реализации** — вызывающий не должен его освобождать
     * и не должен им пользоваться после вызова.
     */
    suspend fun recognise(bitmap: Bitmap): String?
}
