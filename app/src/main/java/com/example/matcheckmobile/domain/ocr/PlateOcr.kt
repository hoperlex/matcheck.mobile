package com.example.matcheckmobile.domain.ocr

import java.io.File

/**
 * Распознавание госномера с фотографии.
 *
 * Контракт жёсткий, и на него опирается вызывающий код: **ни один метод не бросает
 * ничего, кроме `CancellationException`**. Распознавание — украшение: нет Google
 * Play services, не приехал OCR-модуль, битый кадр, мало памяти — всё это
 * возвращает null и логируется, но никогда не мешает добавить фотографию.
 *
 * Два шага разнесены нарочно. [readFrame] обязан отработать ДО того, как на кадр
 * ляжет водяной знак: `MetadataWatermark.applyTo` перезаписывает файл неатомарно,
 * и любое последующее чтение того же файла могло бы попасть на полузаписанный
 * JPEG. Поэтому байты снимаются один раз, а оба прохода распознавания работают
 * уже из них и могут тянуться сколько угодно, не задерживая появление снимка.
 */
interface PlateOcr {

    /** Читает кадр в память целиком. Возвращает null, если прочитать не вышло. */
    suspend fun readFrame(file: File): ByteArray?

    /** Распознаёт номер и возвращает его в кириллице, либо null, если уверенности нет. */
    suspend fun recognise(frame: ByteArray): String?
}
