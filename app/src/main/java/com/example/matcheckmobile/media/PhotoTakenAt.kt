package com.example.matcheckmobile.media

import java.io.File
import java.time.Instant

/**
 * Момент съёмки кадра — время последней записи файла на диск.
 *
 * Зачем не `Instant.now()` в момент подготовки: раньше `taken_at` фото ставил
 * сервер при presign, и на портале заголовок этапа («1 Этап … Время: 12:31»)
 * показывал момент синхронизации. 04.08 на ЖК ВАРШАВСКАЯ LIFE кадры сняты в
 * 12:24–12:30, а после возврата сети у обоих этапов стояло 12:31. Теперь время
 * считает планшет — но брать его надо у файла, а не у момента отправки, иначе
 * при долгом офлайне получится ровно та же ошибка, только на клиенте.
 *
 * `lastModified` — это окончательная запись файла, а не строго нажатие
 * затвора: для кадра с watermark это момент, когда изображение с подписью
 * дописано на диск (совпадает с напечатанным временем до минуты), для
 * документа — запись после EXIF-нормализации. Для заголовка этапа этого
 * достаточно.
 *
 * `lastModified == 0` означает «файла нет или ФС не отдала время» — тогда
 * честнее взять текущее время, чем отправить эпоху 1970 года.
 *
 * Чистая функция, покрывается обычным JVM-тестом.
 */
fun photoTakenAtIso(file: File, now: () -> Instant = Instant::now): String {
    val modifiedAt = file.lastModified()
    return if (modifiedAt > 0L) Instant.ofEpochMilli(modifiedAt).toString() else now().toString()
}
