package com.example.matcheckmobile.data.repository

import com.example.matcheckmobile.data.remote.api.dto.ReconcilePerTypeDto

/**
 * Какие записи сверка велела перезабрать с сервера.
 *
 * Вынесено из [SyncRepository] отдельной функцией не ради красоты, а потому что
 * это единственное место, где решается судьба УСТАРЕВШЕЙ локальной копии, а
 * проверить его внутри репозитория нечем: тот тянет Room, Retrofit и WorkManager,
 * то есть проверяется только на устройстве.
 *
 * Чем это важно. Документ, у которого на портале сорвался разбор, уезжает на
 * планшет пустым — карточка с прочерками. После успешного повторного
 * распознавания сервер помечает его `staleOnClient`, и вернуть инспектору
 * настоящие реквизиты может только перезабор по этому списку. Урони кто-нибудь
 * `staleOnClient` из объединения — планшет продолжит показывать прочерки, а
 * упадёт при этом ровно ничего: `missingOnClient` останется на месте, сверка
 * будет так же бодро писать в лог, и дефект вернётся молча. Ради этого случая
 * функция и существует отдельно.
 *
 * `missingOnClient` — «на сервере есть, у планшета нет вовсе»;
 * `staleOnClient` — «есть у обоих, серверная версия новее».
 * `missingOnServer` сюда НЕ входит: это обратное расхождение, у приёмок и
 * отгрузок оно лечится переотправкой мутации, а у документов игнорируется.
 */
internal fun reconcileRefetchIds(part: ReconcilePerTypeDto): List<String> =
    (part.missingOnClient.map { it.id } + part.staleOnClient.map { it.id }).distinct()
