package com.example.matcheckmobile.data.auth

/**
 * Глобальный флаг «идёт смена аккаунта».
 *
 * Между получением ответа /auth/login нового пользователя и очисткой локальной
 * базы есть окно, в котором фоновый sync мог бы отправить данные ПРОШЛОГО
 * аккаунта уже под НОВЫМ токеном — ровно так приёмки объекта ЗИЛ33 уехали на
 * TEST (инцидент 2026-07). [MatcheckSyncWorker] проверяет этот флаг наравне
 * с наличием сессии и во время переключения молча выходит: после активации
 * новой сессии sync всё равно запускается заново.
 *
 * Флаг снимается в `finally` координатора смены аккаунта, чтобы сбой очистки
 * не оставил приложение без синхронизации навсегда.
 */
object SessionGate {

    @Volatile
    private var switching: Boolean = false

    fun isSwitching(): Boolean = switching

    fun begin() {
        switching = true
    }

    fun end() {
        switching = false
    }
}
