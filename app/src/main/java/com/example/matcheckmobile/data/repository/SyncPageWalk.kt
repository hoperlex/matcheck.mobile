package com.example.matcheckmobile.data.repository

/**
 * Правило обхода страниц дельта-синхронизации.
 *
 * Вынесено отдельной чистой функцией по той же причине, что GroupMaterialsBuilder:
 * правило одно, ошибиться в нём дорого, а проверять его внутри SyncRepository
 * пришлось бы через Room, Retrofit и DataStore разом.
 *
 * Что именно оно стережёт. Основной курсор синхронизации означает «всё до этого
 * момента применено на устройстве». Сохранив его в середине обхода, клиент
 * объявляет применённым то, чего ещё не получил: следующий запрос уйдёт от
 * нового момента, и непрочитанный хвост не приедет уже никогда. Ровно так
 * терялись документы до keyset-пагинации.
 *
 * Оба контракта живут здесь одновременно:
 *   * новый (групповой) — сервер сам говорит «есть продолжение» через
 *     nextPageToken, и пока он непустой, курсор двигать нельзя;
 *   * старый — сервер о продолжении не сообщает вовсе, и признаком служит
 *     полностью заполненная страница; курсор двигается после каждой.
 */
internal data class PageDecision(
    /** Токен следующей страницы. null — обход страниц снимка закончен. */
    val pageToken: String?,
    /** Разрешено ли сохранить основной курсор прямо сейчас. */
    val commitCursor: Boolean,
    /** Завершён ли проход целиком (больше запросов не нужно). */
    val done: Boolean,
)

/**
 * @param nextPageToken значение из ответа сервера; null у старого сервера и на
 *   последней странице нового.
 * @param hasMoreByPageSize прежний признак «страница полная, наверняка есть ещё»
 *   — единственное, чем располагает старый контракт.
 */
internal fun decidePageStep(nextPageToken: String?, hasMoreByPageSize: Boolean): PageDecision {
    if (nextPageToken != null) {
        // Середина снимка: страницу применили, но проход не закончен.
        return PageDecision(pageToken = nextPageToken, commitCursor = false, done = false)
    }
    // Страница последняя в своём проходе — курсор наконец можно сдвинуть.
    // done определяется старым признаком: у нового сервера пустой nextPageToken
    // уже означает конец, а лишний холостой запрос по полной странице безвреден.
    return PageDecision(pageToken = null, commitCursor = true, done = !hasMoreByPageSize)
}
